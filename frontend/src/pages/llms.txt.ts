import type { APIRoute } from "astro";
import { formatPrice, loadContent, subjectNames } from "../lib/content";
import { absoluteUrl, siteOrigin } from "../lib/site";

export const GET: APIRoute = () => {
  const { provider, subjects, plans } = loadContent();
  const names = subjectNames(loadContent());
  const lines = [
    `# ${provider.name}`,
    "",
    `> CBSE Class 10 home tuition by ${provider.tutor_name} in ${provider.service_localities.join(" and ")}. The trial is ${formatPrice(provider.trial.fee_paise)} and lasts ${provider.trial.duration_minutes} minutes. A parent or guardian must confirm consent with a one-time code before a booking is created.`,
    "",
    "## Provider",
    "",
    `- Provider id: ${provider.id}`,
    `- Content version: ${provider.version}`,
    `- Last updated: ${provider.last_updated}`,
    `- Tutor: ${provider.tutor_name}`,
    `- Qualifications: ${provider.qualifications.join("; ")}`,
    `- Experience: ${provider.experience_years} years`,
    `- Boards: ${provider.boards.join(", ")}`,
    `- Classes: ${provider.classes.join(", ")}`,
    `- Teaching mode: ${provider.teaching_mode.join(", ")}`,
    `- Languages: ${provider.languages.join(", ")}`,
    `- Service localities: ${provider.service_localities.join(", ")}`,
    `- Availability: ${provider.availability.days.join(", ")} ${provider.availability.window} ${provider.availability.timezone}`,
    `- WhatsApp: ${provider.contact.whatsapp}`,
    `- Email: ${provider.contact.email}`,
    "",
    "## Subjects",
    "",
    ...subjects.map((subject) => `- ${subject.name} (${subject.id}), ${subject.board} Class ${subject.class}`),
    "",
    "## Plans",
    "",
    ...plans.flatMap((plan) => [
      `- ${plan.name} (${plan.id}): ${formatPrice(plan.price_paise, plan.currency)}; ${plan.session_minutes}-minute sessions${plan.sessions_per_week ? `, ${plan.sessions_per_week} per week` : ""}${plan.duration_days ? `, ${plan.duration_days} days` : ""}; subjects: ${plan.subjects.map((id) => names[id] ?? id).join(", ")}; cancellation: ${plan.cancellation}`,
    ]),
    "",
    "## Pages",
    "",
    ...["", "subjects/", "plans/", "book/", "enquiry/", "booking/"].map((path) => `- ${absoluteUrl(path)}`),
    `- ${absoluteUrl("policies/privacy/")}`,
    `- ${absoluteUrl("policies/consent/")}`,
    `- ${absoluteUrl("policies/cancellation-refund/")}`,
    "",
    "## API",
    "",
    `- API base: ${absoluteUrl("api/v1/")}`,
    `- OpenAPI 3.1: ${absoluteUrl("openapi.yaml")}`,
    `- Schema directory: ${absoluteUrl("spec/models/")}`,
    "- Public reads: GET /api/v1/provider, /api/v1/subjects, /api/v1/plans",
    "- Slots: GET /api/v1/slots?locality_code=...&from=...&to=...",
    "- Holds: POST /api/v1/slots/{slot_id}/hold with Idempotency-Key",
    "- Consent: POST /api/v1/consent/requests, then POST /api/v1/consent/requests/{request_id}/verify",
    "- Booking: POST /api/v1/trial-bookings with hold_id, consent_token, student, subjects, locality_code and Idempotency-Key",
    "- Booking lookup and cancellation require the bearer booking access token.",
    "",
    "## MCP",
    "",
    `- MCP endpoint: ${absoluteUrl("mcp")}`,
    "- Tools: get_provider, get_plans, check_trial_slots, request_parent_consent, verify_parent_consent, hold_trial_slot, book_trial, create_enquiry",
    "- The agent must never invent an OTP. The parent must provide the code.",
    "- The parent phone number and consent token are never returned in a booking response.",
    "",
    "## Policies",
    "",
    `- Privacy: ${absoluteUrl("policies/privacy/")}`,
    `- Consent: ${absoluteUrl("policies/consent/")}`,
    `- Cancellation and refund: ${absoluteUrl("policies/cancellation-refund/")}`,
    "",
    `Site origin: ${siteOrigin}`,
    "",
  ];
  return new Response(lines.join("\n"), {
    headers: { "content-type": "text/plain; charset=utf-8" },
  });
};
